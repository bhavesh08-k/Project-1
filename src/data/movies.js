export const allGenres = [...new Set(movies.flatMap((m) => m.genres))].sort()
export const allLanguages = [...new Set(movies.map((m) => m.language))].sort()

export function getMovieById(id) {
  return movies.find((m) => m.id === id) ?? null
}

export function getNowShowing() {
  return movies.filter((m) => m.status === 'now-showing')
}

export function getComingSoon() {
  return movies.filter((m) => m.status === 'coming-soon')
}

export function getPopular() {
  return [...movies].sort((a, b) => b.popularity - a.popularity).slice(0, 8)
}

export function getFeatured() {
  return movies.find((m) => m.featured) ?? movies[0]
}
